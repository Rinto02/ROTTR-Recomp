#!/usr/bin/env bash
# ============================================================
# setup-prefix.sh — Create & configure Wine prefix for ROTTR
# ============================================================
# Sets up a Wine prefix with DXVK installed, registry tweaks
# applied, and ROTTR-optimized configuration.
#
# Usage: bash scripts/setup-prefix.sh [GAME_DIR]
#   GAME_DIR: Path to your ROTTR game files (optional, can copy later)
# ============================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
GAME_DIR="${1:-}"

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m'

log()   { echo -e "${GREEN}[ROTTR]${NC} $*"; }
warn()  { echo -e "${YELLOW}[WARN]${NC} $*"; }
error() { echo -e "${RED}[ERROR]${NC} $*"; exit 1; }

# --- Configuration ---
WINEPREFIX="$HOME/.rottr-prefix"
DXVK_DIR="$HOME/.local/share/dxvk"
GAME_INSTALL_DIR="$WINEPREFIX/drive_c/Games/ROTTR"

# --- Source Box64 environment ---
log "Loading Box64 configuration..."
source "$PROJECT_DIR/config/box64.env"

# --- Create Wine prefix ---
log "Creating Wine prefix at: $WINEPREFIX"
export WINEPREFIX
export WINEARCH=win64

if [ ! -d "$WINEPREFIX" ]; then
    wine wineboot --init 2>/dev/null
    log "Wine prefix created."
else
    log "Wine prefix already exists."
fi

# --- Install DXVK into prefix ---
log "Installing DXVK into Wine prefix..."
if [ -f "$DXVK_DIR/setup_dxvk.sh" ]; then
    cd "$DXVK_DIR"
    bash setup_dxvk.sh install 2>/dev/null
    log "DXVK installed into prefix."
elif [ -d "$DXVK_DIR/x64" ]; then
    # Manual DXVK installation
    SYSTEM32="$WINEPREFIX/drive_c/windows/system32"
    for dll in d3d9 d3d10core d3d11 dxgi; do
        if [ -f "$DXVK_DIR/x64/${dll}.dll" ]; then
            cp -f "$DXVK_DIR/x64/${dll}.dll" "$SYSTEM32/"
            log "  Copied ${dll}.dll"
        fi
    done
    log "DXVK DLLs copied manually."
else
    warn "DXVK not found at $DXVK_DIR. Run setup-termux.sh first."
fi

# --- Apply DXVK config ---
log "Applying DXVK configuration..."
cp -f "$PROJECT_DIR/config/dxvk.conf" "$WINEPREFIX/drive_c/"
log "DXVK config placed at C:\\"

# --- Apply Wine registry tweaks ---
log "Applying Wine registry overrides..."
wine regedit "$PROJECT_DIR/config/wine.reg" 2>/dev/null
log "Registry overrides applied."

# --- Create game directory ---
mkdir -p "$GAME_INSTALL_DIR"

# --- Write optimized ROTTR settings ---
log "Writing optimized ROTTR graphics settings..."
ROTTR_CONFIG="$GAME_INSTALL_DIR/ROTTR.ini"
cat > "$ROTTR_CONFIG" << 'ROTTR_INI'
; ============================================================
; Rise of the Tomb Raider — Android Optimized Settings
; Generated by ROTTR-Recomp setup-prefix.sh
; ============================================================

[Display]
; 720p for best mobile performance
FullScreen=true
Width=1280
Height=720
RefreshRate=60
VSync=0
Stereo=false
ExclusiveFullscreen=false

[Graphics]
; Lowest/Low preset optimized for mobile Vulkan
TextureQuality=1
TextureFilter=1
Shadow=0
ShadowResolution=0
AmbientOcclusion=0
DepthOfField=0
Tessellation=0
ScreenSpaceReflections=0
DynamicFoliage=0
Bloom=1
MotionBlur=0
LensFlare=0
AntiAliasing=1
AntiAliasingType=0
LevelOfDetail=0
PureHair=0
PureHairQuality=0
VolumetricLighting=0
SunSoftShadow=0
PointSoftShadow=0
ScreenSpaceContactShadow=0

[Rendering]
; Use DX11 (DXVK translates to Vulkan)
RenderingAPI=DirectX11

[Performance]
; Frame limiter (let DXVK handle via dxvk.conf)
MaxFPS=30
ROTTR_INI

log "Settings written to: $ROTTR_CONFIG"

# --- Copy game files if provided ---
if [ -n "$GAME_DIR" ] && [ -d "$GAME_DIR" ]; then
    log "Copying game files from: $GAME_DIR"
    log "This may take a while for ~25GB of data..."
    cp -r "$GAME_DIR"/* "$GAME_INSTALL_DIR/"
    log "Game files copied."
elif [ -n "$GAME_DIR" ]; then
    warn "Game directory not found: $GAME_DIR"
    warn "Copy your game files manually to: $GAME_INSTALL_DIR"
else
    log "No game directory specified."
    log "Copy your ROTTR game files to: $GAME_INSTALL_DIR"
fi

# --- Summary ---
echo ""
echo -e "${CYAN}============================================${NC}"
echo -e "${CYAN}  Wine Prefix Setup Complete${NC}"
echo -e "${CYAN}============================================${NC}"
echo ""
echo -e "  Prefix:    $WINEPREFIX"
echo -e "  Game dir:  $GAME_INSTALL_DIR"
echo -e "  DXVK conf: $WINEPREFIX/drive_c/dxvk.conf"
echo -e "  ROTTR ini: $ROTTR_CONFIG"
echo ""
if [ -f "$GAME_INSTALL_DIR/ROTTR.exe" ]; then
    echo -e "  Game binary found! Ready to launch."
    echo -e "  Next step: ${GREEN}bash scripts/run-rottr.sh${NC}"
else
    echo -e "  ${YELLOW}Game files not found yet.${NC}"
    echo -e "  Copy your ROTTR files to:"
    echo -e "    ${CYAN}$GAME_INSTALL_DIR${NC}"
    echo -e "  Then run: ${GREEN}bash scripts/run-rottr.sh${NC}"
fi
echo ""
